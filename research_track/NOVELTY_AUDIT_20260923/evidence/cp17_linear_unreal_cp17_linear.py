#!/usr/bin/env python3
"""Independent exact-geometric transfer for the CP17 Syracuse variable.

Usage: python3 cp17_linear.py [max_n (default 11)] [decimal_precision (default 65)]
No Monte Carlo or truncation of the geometric A law: the finite cyclic kernel
is exactly w(a)=2**(-a)/(1-2**(-L)), 1<=a<=L. Decimal arithmetic is used for
large n, with errors from rounding controlled by the chosen precision.
"""
from decimal import Decimal, localcontext
from fractions import Fraction
import json
import sys


def cycle_step(previous, n, one, two):
    """Return probabilities indexed by ordinary residues modulo 3**n."""
    N = 3 ** n
    L = 2 * (N // 3)
    zero = one - one
    r = [zero] * L
    powers = [0] * L
    u = 1
    for k in range(L):
        powers[k] = u
        if u % 3 == 1:
            r[k] = previous[(u - 1) // 3]
        u = (u * 2) % N
    assert u == 1 and len(set(powers)) == L
    # p(k)=sum_{a>=1}2^-a r(k+a mod L), hence
    # 2*p(k)=r(k+1)+p(k+1).  The periodic solution satisfies
    # p(0)=sum_{a=1}^L 2^-a*r(a mod L)/(1-2^-L).
    half = one / two
    weight = one
    p0 = zero
    for a in range(1, L + 1):
        weight *= half
        p0 += weight * r[a % L]
    p0 /= one - weight
    p = [zero] * L
    p[0] = p0
    for k in range(L - 1, 0, -1):
        p[k] = (r[(k + 1) % L] + p[(k + 1) % L]) * half
    out = [zero] * N
    for k in range(L):
        out[powers[k]] = p[k]
    return out


def compute(max_n=11, precision=65):
    assert max_n >= 2 and precision >= 30
    # Independently validate with exact Fraction arithmetic at n=1,...,4.
    fq = [Fraction(1)]
    exact = []
    exact_p2 = None
    for n in (1, 2, 3, 4):
        fq = cycle_step(fq, n, Fraction(1), Fraction(2))
        exact.append(str(3 ** n * sum(x*x for x in fq)))
        if n == 2:
            exact_p2 = [str(x) for x in fq]
    assert exact == ['5/3', '15/7', '177005/67963',
                     '6626070796594781675/2159281421340253987'], exact
    rows = []
    # Every operation, including the geometric sum, uses the full period.
    with localcontext() as ctx:
        ctx.prec = precision
        one, two = Decimal(1), Decimal(2)
        prev = [one]
        last = one
        for n in range(1, max_n + 1):
            old = prev
            prev = cycle_step(old, n, one, two)
            norm = sum(prev, Decimal(0))
            # Avoid numerical cancellation of chi_n - chi_(n-1) by
            # working with ample guard digits (precision parameter).
            chi = Decimal(3 ** n) * sum((v*v for v in prev), Decimal(0))
            energy = chi - last
            # Orthogonal increment of the three-adic density martingale.
            # This computes E_n without subtracting nearly equal chi values.
            base = 3 ** (n-1)
            third = one / Decimal(3)
            direct_E = Decimal(3 ** n) * sum(
                ((v-old[i % base]*third)**2 for i, v in enumerate(prev)), Decimal(0))
            assert abs(direct_E-energy) < Decimal(10) ** (-precision+10), (n, direct_E, energy)
            rows.append(dict(n=n, chi=str(+chi), E=str(+direct_E),
                             E_via_difference=str(+energy),
                             mass_error=str(norm-one),
                             cyclic_order=2*3**(n-1)))
            last = chi
        assert abs(Decimal(rows[0]['chi'])-Decimal(5)/3) < Decimal(10)**(-precision+7)
        assert abs(Decimal(rows[1]['chi'])-Decimal(15)/7) < Decimal(10)**(-precision+7)
        obj = {
            'method': 'full-period geometric kernel on cyclic group generated by 2; decimal arithmetic, no probabilistic cutoff',
            'decimal_precision': precision, 'max_n': max_n,
            'exact_checks': {'chi_1':exact[0], 'chi_2':exact[1],
                             'chi_3':exact[2], 'chi_4':exact[3],
                             'p_2_by_residue_0_to_8':exact_p2},
            'rows':rows,
            'limit': {'status':'existence unproved; no justified numerical extrapolation',
                      'candidate':'7/15 (early-data hypothesis, n=10..15 disagree with short-scale stabilization)',
                      'candidate_decimal':str(Decimal(7)/Decimal(15)),
                      'last_E_minus_candidate':str(Decimal(rows[-1]['E'])-Decimal(7)/Decimal(15))},
            'identities': {'chi_n':'sum_{j=0}^n E_j, E_0=1',
                           'E_n':'3^n P(X_n=X_n_prime mod 3^n) - 3^(n-1) P(X_(n-1)=X_(n-1)_prime mod 3^(n-1))'},
        }
    with open('cp17_linear.json','w',encoding='utf-8') as f:
        json.dump(obj,f,indent=2,ensure_ascii=False)
    print('Exact Fraction checks:', ', '.join(f'chi_{i+1}={v}' for i, v in enumerate(exact)))
    print('n   chi_n                         E_n                           E_n - 7/15')
    with localcontext() as ctx:
        ctx.prec = 30
        for row in rows:
            print(f"{row['n']:2}  {Decimal(row['chi']):.14f}  {Decimal(row['E']):.14f}  {Decimal(row['E'])-Decimal(7)/15:+.12f}")
    return obj

if __name__ == '__main__':
    compute(int(sys.argv[1]) if len(sys.argv)>1 else 11,
            int(sys.argv[2]) if len(sys.argv)>2 else 65)
